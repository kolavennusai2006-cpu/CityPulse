@app.route("/api/citypulse", methods=["GET"])
def citypulse():

    zones, error = get_all_zones()

    if error:
        return jsonify({
            "success": False,
            "error": error
        }), 500

    # --------------------------------------------------------
    # CITY RISK
    # --------------------------------------------------------

    risk_scores = [
        zone.get("risk_score", 0)
        for zone in zones
    ]

    city_risk_score = max(risk_scores) if risk_scores else 0

    city_status = calculate_city_status(
        city_risk_score
    )

    # --------------------------------------------------------
    # ZONE INTELLIGENCE
    # --------------------------------------------------------

    zone_outputs = []

    for zone in zones:

        zone_id = zone.get("zone_id")

        investigation = agent.investigate(
            zone_id
        )

        zone_outputs.append({

            "zone_id": zone_id,

            "status": zone.get(
                "status",
                "NORMAL"
            ),

            "risk_score": zone.get(
                "risk_score",
                0
            ),

            "signals_detected": zone.get(
                "signals_detected",
                []
            ),

            "investigation": investigation
        })

    # --------------------------------------------------------
    # PRIORITY ZONE
    # --------------------------------------------------------

    priority_zone = None

    if zones:

        priority_zone = max(
            zones,
            key=lambda z: z.get(
                "risk_score",
                0
            )
        )

    # --------------------------------------------------------
    # CIVIC BRIEF
    # --------------------------------------------------------

    civic_brief = None

    if priority_zone:

        priority_zone_id = priority_zone.get(
            "zone_id"
        )

        explanation = agent.explain(
            priority_zone_id
        )

        brief_result = generate_civic_brief(
            explanation
        )

        if brief_result.get("success"):

            civic_brief = brief_result.get(
                "brief"
            )

        else:

            civic_brief = (
                "Unable to generate civic brief."
            )

    # --------------------------------------------------------
    # RESPONSE
    # --------------------------------------------------------

    return jsonify({

        "success": True,

        "city_status": city_status,

        "city_risk_score": city_risk_score,

        "priority_zone": (
            priority_zone.get("zone_id")
            if priority_zone
            else None
        ),

        "zones": zone_outputs,

        "civic_brief": civic_brief

    })


