@app.route(
    "/api/agent/question",
    methods=["POST"]
)
def agent_question():

    data = request.get_json(
        silent=True
    ) or {}

    zone_id = data.get(
        "zone_id",
        "ZONE_A"
    )

    question = str(
        data.get(
            "question",
            ""
        )
    ).strip()

    if not question:

        return jsonify({
            "success": False,
            "error": "Question is required."
        }), 400

    # --------------------------------------------------------
    # Load structured evidence
    # --------------------------------------------------------

    investigation = agent.investigate(
        zone_id
    )

    evidence = agent.verify(
        zone_id
    )

    timeline = get_event_timeline(
        zone_id
    )

    recovery = get_recovery_status(
        zone_id
    )

    # --------------------------------------------------------
    # Simple intent detection
    # --------------------------------------------------------

    question_lower = question.lower()

    answer = ""

    if (
        "start" in question_lower
        or "when" in question_lower
    ):

        start = (
            timeline
            .get("event_start")
            if isinstance(
                timeline,
                dict
            )
            else None
        )

        if start:

            answer = (
                f"The reconstructed event in "
                f"{zone_id.replace('_', ' ')} "
                f"starts at approximately "
                f"+{start.get('time_offset_minutes', '—')} "
                f"minutes."
            )

        else:

            answer = (
                "No confirmed event start "
                "was found in the available "
                "reconstructed timeline."
            )

    elif (
        "signal" in question_lower
        or "what changed" in question_lower
    ):

        signals = investigation.get(
            "signals_detected",
            []
        )

        answer = (
            "The detected signals are: "
            + (
                ", ".join(signals)
                if signals
                else "none"
            )
            + "."
        )

    elif (
        "stage" in question_lower
        or "lifecycle" in question_lower
    ):

        lifecycle = (
            recovery.get(
                "lifecycle_stage"
            )
            or investigation.get(
                "event_lifecycle",
                {}
            ).get(
                "lifecycle_stage"
            )
            or "MONITORING"
        )

        answer = (
            f"The current event lifecycle "
            f"stage is {lifecycle.replace('_', ' ')}."
        )

    elif (
        "risk" in question_lower
        or "flag" in question_lower
        or "why" in question_lower
    ):

        answer = (
            f"{zone_id.replace('_', ' ')} "
            f"has a risk score of "
            f"{investigation.get('risk_score', 0)}. "
            f"{evidence.get('reason', '')}"
        )

    else:

        answer = (
            "Based on the current structured "
            "CityPulse evidence, the system has "
            f"identified {len(investigation.get('signals_detected', []))} "
            "active civic signals in "
            f"{zone_id.replace('_', ' ')}. "
            "The evidence should be interpreted "
            "as observed associations rather "
            "than confirmed causation."
        )

    return jsonify({

        "success": True,

        "agent_action": "QUESTION",

        "zone_id": zone_id,

        "question": question,

        "answer": answer,

        "evidence": evidence,

        "investigation": investigation,

        "timeline": timeline,

        "recovery": recovery

    })


