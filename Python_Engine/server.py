@app.route(
    "/api/simulation",
    methods=["POST"]
)
def simulation():

    data = request.get_json(
        silent=True
    ) or {}

    zone_id = data.get(
        "zone_id",
        "ZONE_A"
    )

    signal = data.get(
        "signal",
        "rainfall_mm"
    )

    percentage_change = data.get(
        "percentage_change",
        0
    )

    # --------------------------------------------------------
    # Validate percentage
    # --------------------------------------------------------

    try:

        percentage_change = float(
            percentage_change
        )

    except (
        TypeError,
        ValueError
    ):

        return jsonify({
            "success": False,
            "error": (
                "percentage_change must "
                "be a number."
            )
        }), 400

    # --------------------------------------------------------
    # Run actual Member 2 simulation engine
    # --------------------------------------------------------

    try:

        result = simulate_zone_change(
            zone_id,
            signal,
            percentage_change
        )

    except Exception as error:

        return jsonify({

            "success": False,

            "error": str(error)

        }), 500

    return jsonify({

        "success": True,

        "agent_action": "SIMULATE",

        "result": result

    })


