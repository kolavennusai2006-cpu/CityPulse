def get_all_zones():
    """
    Load the latest CityPulse intelligence generated by Member 1.
    """
    result = load_citypulse_data()

    if not result.get("success"):
        return None, result.get(
            "error",
            "Unable to load CityPulse intelligence."
        )

    return result.get("data", []), None


def find_zone(zone_id):
    """
    Find one zone from the latest CityPulse intelligence.
    """
    zones, error = get_all_zones()

    if error:
        return None, error

    for zone in zones:
        if zone.get("zone_id") == zone_id:
            return zone, None

    return None, f"Zone {zone_id} was not found."


def calculate_city_status(risk_score):
    """
    Convert city risk score into the CityPulse status.
    """

    if risk_score >= 75:
        return "CRITICAL"

    if risk_score >= 50:
        return "EMERGING"

    if risk_score >= 30:
        return "WATCH"

    return "NORMAL"


